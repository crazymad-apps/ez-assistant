import { compatibilityHeaders } from "@ez-assistant/protocol";
import { expect, test } from "@playwright/test";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

test("F05 previews message and document images, downloads exact bytes and retries missing files on the actual Host OS", async ({ page }, info) => {
  const host = JSON.parse(process.env.EZ_ASSISTANT_E2E_BOOTSTRAP!) as { base_url: string; access_token: string };
  const headers = { ...compatibilityHeaders(), Authorization: `Bearer ${host.access_token}`, "Content-Type": "application/json" };
  const directory = join(process.env.EZ_ASSISTANT_E2E_NEW_WORKSPACE!, "F05 中文 空格");
  await mkdir(directory);
  const image_path = join(directory, "产物 #100%.png");
  const document_path = join(directory, "说明 文档.md");
  const bytes = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGMwaPj/HwAFQgKv8Qz/1QAAAABJRU5ErkJggg==", "base64");
  await writeFile(image_path, bytes);
  await writeFile(document_path, "# F05 文档\n\n![文档内图片](./产物%20%23100%25.png)\n");
  const workspace_response = await fetch(`${host.base_url}/commands`, { method: "POST", headers, body: JSON.stringify({ request_id: crypto.randomUUID(), command: { scope: "runtime", payload: { type: "register_workspace", payload: { label: "F05 资源", primary_directory: directory, additional_directories: [] } } } }) });
  expect(workspace_response.status).toBe(200);
  const workspace = (await workspace_response.json()).result.payload.payload.workspace;
  const created = await fetch(`${host.base_url}/commands`, { method: "POST", headers, body: JSON.stringify({ request_id: crypto.randomUUID(), command: { scope: "runtime", payload: { type: "create_session", payload: { title: "F05 资源测试", model_selection: null, workspace_id: workspace.workspace_id } } } }) });
  expect(created.status).toBe(200);
  const login = await fetch(`${host.base_url}/auth/login`, { method: "POST", headers, body: JSON.stringify({ method: "desktop" }) });
  const { token } = await login.json();
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto(`${host.base_url}/#token=${encodeURIComponent(token)}`);
  await page.getByText("F05 资源测试", { exact: true }).first().click();
  await page.getByLabel("输入消息", { exact: true }).fill(`F05_RESOURCES\n![消息产物](${pathToFileURL(image_path).href})\n\n[说明文档](${pathToFileURL(document_path).href})`);
  await page.getByRole("button", { name: "发送消息", exact: true }).click();
  const message_image = page.getByRole("img", { name: "消息产物", exact: true }).last();
  await expect(message_image).toBeVisible();
  await expect.poll(() => message_image.evaluate((node) => (node as HTMLImageElement).naturalWidth)).toBe(1);
  await message_image.click();
  const panel = page.getByRole("complementary", { name: "资源栏" });
  await expect(panel.getByRole("tab", { name: /产物 #100%.png/ })).toBeVisible();
  await expect.poll(() => panel.locator("img").last().evaluate((node) => (node as HTMLImageElement).naturalWidth)).toBe(1);
  await page.getByRole("button", { name: "更多资源操作", exact: true }).click();
  await expect(page.getByRole("menuitem", { name: /Finder|资源管理器|系统应用/ })).toHaveCount(0);
  const downloading = page.waitForEvent("download");
  await page.getByRole("menuitem", { name: "下载文件", exact: true }).click();
  const download = await downloading;
  expect(download.suggestedFilename()).toBe("产物 #100%.png");
  expect(await readFile((await download.path())!)).toEqual(bytes);
  await page.getByRole("button", { name: "说明文档", exact: true }).click();
  await expect(panel.getByRole("heading", { name: "F05 文档", exact: true })).toBeVisible();
  const embedded = panel.getByRole("img", { name: "文档内图片", exact: true });
  await expect.poll(() => embedded.evaluate((node) => (node as HTMLImageElement).naturalWidth)).toBe(1);
  await page.screenshot({ path: info.outputPath("resources-preview.png") });
  await unlink(image_path);
  await page.reload();
  await page.getByText("F05 资源测试", { exact: true }).first().click();
  await expect(page.getByRole("button", { name: "重试图片", exact: true })).toBeVisible();
  await writeFile(image_path, bytes);
  await page.getByRole("button", { name: "重试图片", exact: true }).click();
  await expect.poll(() => page.getByRole("img", { name: "消息产物", exact: true }).last().evaluate((node) => (node as HTMLImageElement).naturalWidth)).toBe(1);
  const outside = await fetch(`${host.base_url}/sessions/${(await created.json()).result.payload.payload.session.session_id}/resource-files/preview`, { method: "POST", headers, body: JSON.stringify({ locator: { root: { type: "workspace_primary" }, relative_path: "../outside.txt" } }) });
  expect(outside.ok).toBe(false);
});
